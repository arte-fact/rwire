/// Payload data from a client event.
///
/// Different event types provide different payload types:
/// - `input`/`change` on `<input>`/`<textarea>` → `Text(value)`
/// - `click` on element with `data-*` attrs → `Data(attrs)`
/// - `submit` on `<form>` → `Form(field_values)`
#[derive(Debug, Clone)]
pub enum EventPayload {
    /// Text value from input.value or textarea.value
    Text(String),
    /// Data attributes from the clicked element (data-id="5" → {"id": "5"})
    Data(HashMap<String, String>),
    /// Form field values from form submission
    Form(HashMap<String, String>),
    /// No payload data
    Empty,
}

/// Context passed to handlers with 2-parameter signatures.
///
/// Provides access to event payload data such as input values, data attributes,
/// and form field values. The payload is parsed lazily on first access.
///
/// Also provides access to handler parameter bytes for ItemRef-based handlers.
///
/// # Example
///
/// ```ignore
/// #[handler]
/// fn add_todo(state: &mut TodoState, ctx: &EventContext) {
///     if let Some(text) = ctx.text() {
///         state.items.push(Todo::new(text.to_string()));
///     }
/// }
///
/// #[handler]
/// fn delete_item(state: &mut TodoState, ctx: &EventContext) {
///     if let Some(id) = ctx.data("id").and_then(|s| s.parse().ok()) {
///         state.items.retain(|item| item.id != id);
///     }
/// }
///
/// // ItemRef-based handler (cleaner API)
/// #[handler]
/// fn toggle_item(state: &mut TodoState, ctx: &EventContext) {
///     if let Some(item_ref) = ctx.item_ref::<TodoItem>() {
///         if let Some(item) = item_ref.get_mut(&mut state.items) {
///             item.done = !item.done;
///         }
///     }
/// }
/// ```
pub struct EventContext {
    /// Raw payload bytes from the client (JSON for form/text events)
    raw: Vec<u8>,
    /// Lazily parsed payload
    parsed: OnceLock<EventPayload>,
    /// Handler parameter bytes (for ItemRef-based handlers)
    param_bytes: Vec<u8>,
    /// A client navigation the handler requested via `navigate`/`replace_route`,
    /// flushed to this connection after the handler's synced update.
    navigation: Cell<Option<Navigation>>,
    /// The connection's session id — app-level identity for shared-state
    /// handlers (presence, membership, per-user authorization).
    session: Option<String>,
    /// Who the connection belongs to, under delegated authentication.
    identity: Option<Identity>,
    /// Set by `defer()`: the handler claimed this action for later resolution.
    deferred: Cell<bool>,
    /// The action this event drives, if dispatched through the real event loop.
    /// Present only there (route/synthetic/test contexts leave it `None`), so
    /// `defer()` can mark the action `Loading` and mint a `Resolver`.
    action: Option<ActionSlot>,
    /// The connection's tasks, for [`EventContext::spawn`]. Present when the
    /// context comes from a live connection (events, routes, `on_connect`).
    tasks: Option<ConnectionTasks>,
}

/// The tokio tasks a connection started through [`EventContext::spawn`]:
/// aborted when the connection closes, whatever the way (client gone,
/// heartbeat, error, server shutdown).
#[derive(Clone, Default)]
pub(crate) struct ConnectionTasks(Arc<std::sync::Mutex<TaskSlot>>);

#[derive(Default)]
struct TaskSlot {
    handles: Vec<tokio::task::AbortHandle>,
    closed: bool,
}

impl ConnectionTasks {
    fn lock(&self) -> std::sync::MutexGuard<'_, TaskSlot> {
        self.0.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// Spawn `fut` on the current tokio runtime, owned by the connection.
    /// Refused (`false`, `fut` dropped unpolled) once the connection closed.
    fn spawn<F>(&self, fut: F) -> bool
    where
        F: std::future::Future<Output = ()> + Send + 'static,
    {
        let mut slot = self.lock();
        if slot.closed {
            return false;
        }
        // Forget the tasks that already ended, so a long connection that
        // spawns often keeps a bounded list.
        slot.handles.retain(|h| !h.is_finished());
        slot.handles.push(tokio::spawn(fut).abort_handle());
        true
    }

    /// Abort every task and refuse new ones.
    pub(crate) fn close(&self) {
        let handles = {
            let mut slot = self.lock();
            slot.closed = true;
            std::mem::take(&mut slot.handles)
        };
        for h in handles {
            h.abort();
        }
    }

    /// How many tasks are still running (tests).
    #[cfg(test)]
    fn running(&self) -> usize {
        self.lock()
            .handles
            .iter()
            .filter(|h| !h.is_finished())
            .count()
    }
}

/// What `defer()` needs to drive the action lifecycle: the shared-state handle to
/// broadcast phase changes through, and this action's key.
struct ActionSlot {
    shared: Arc<SharedServerState>,
    key: ActionKey,
    /// Shared with the resolvers `defer()` hands out, so a resolution made before the handler
    /// returns is applied by `EventContext::settle_deferred` rather than overwritten by `Loading`.
    settlement: crate::actions::SettlementCell,
}

/// A server-initiated client navigation requested from a handler.
pub(crate) struct Navigation {
    pub url: String,
    pub replace: bool,
}

impl EventContext {
    /// Create a new EventContext from raw payload bytes.
    pub fn new(raw: Vec<u8>) -> Self {
        Self {
            raw,
            parsed: OnceLock::new(),
            param_bytes: Vec::new(),
            navigation: Cell::new(None),
            session: None,
            identity: None,
            deferred: Cell::new(false),
            action: None,
            tasks: None,
        }
    }

    /// Create a new EventContext with both payload and param bytes.
    pub fn new_with_params(raw: Vec<u8>, param_bytes: Vec<u8>) -> Self {
        Self {
            raw,
            parsed: OnceLock::new(),
            param_bytes,
            navigation: Cell::new(None),
            session: None,
            identity: None,
            deferred: Cell::new(false),
            action: None,
            tasks: None,
        }
    }

    /// Create an empty EventContext (no payload).
    pub fn empty() -> Self {
        Self {
            raw: Vec::new(),
            parsed: OnceLock::new(),
            param_bytes: Vec::new(),
            navigation: Cell::new(None),
            session: None,
            identity: None,
            deferred: Cell::new(false),
            action: None,
            tasks: None,
        }
    }

    /// Request a client navigation: push `url` onto history (back returns here).
    /// Use this when a handler creates or selects a resource whose URL is only
    /// known server-side — the URL updates after the handler's DOM update lands.
    pub fn navigate(&self, url: impl Into<String>) {
        self.navigation.set(Some(Navigation {
            url: url.into(),
            replace: false,
        }));
    }

    /// Request a client navigation that replaces the current history entry.
    pub fn replace_route(&self, url: impl Into<String>) {
        self.navigation.set(Some(Navigation {
            url: url.into(),
            replace: true,
        }));
    }

    /// Take the navigation the handler requested, if any (server-internal).
    pub(crate) fn take_navigation(&self) -> Option<Navigation> {
        self.navigation.take()
    }

    /// Create an EventContext with a text payload (e.g., a route path).
    ///
    /// This is used internally by the server to deliver route change messages
    /// to route handlers via `ctx.text()`.
    pub fn from_text(text: &str) -> Self {
        let json = serde_json::json!({"t": "text", "v": text});
        Self::new(json.to_string().into_bytes())
    }

    /// Get the parsed payload, parsing lazily if needed.
    pub fn payload(&self) -> &EventPayload {
        self.parsed.get_or_init(|| self.parse_payload())
    }

    /// Parse the raw payload bytes into an EventPayload.
    fn parse_payload(&self) -> EventPayload {
        if self.raw.is_empty() {
            return EventPayload::Empty;
        }

        // Try to parse as JSON
        let json_str = match std::str::from_utf8(&self.raw) {
            Ok(s) => s,
            Err(_) => return EventPayload::Empty,
        };

        // Parse JSON object with type discriminator
        let parsed: serde_json::Value = match serde_json::from_str(json_str) {
            Ok(v) => v,
            Err(_) => return EventPayload::Empty,
        };

        let obj = match parsed.as_object() {
            Some(o) => o,
            None => return EventPayload::Empty,
        };

        let payload_type = obj.get("t").and_then(|v| v.as_str()).unwrap_or("");
        let value = obj.get("v");

        match payload_type {
            "text" => {
                if let Some(s) = value.and_then(|v| v.as_str()) {
                    EventPayload::Text(s.to_string())
                } else {
                    EventPayload::Empty
                }
            }
            "data" => {
                if let Some(obj) = value.and_then(|v| v.as_object()) {
                    let map: HashMap<String, String> = obj
                        .iter()
                        .filter_map(|(k, v)| v.as_str().map(|s| (k.clone(), s.to_string())))
                        .collect();
                    EventPayload::Data(map)
                } else {
                    EventPayload::Empty
                }
            }
            "form" => {
                if let Some(obj) = value.and_then(|v| v.as_object()) {
                    let map: HashMap<String, String> = obj
                        .iter()
                        .filter_map(|(k, v)| v.as_str().map(|s| (k.clone(), s.to_string())))
                        .collect();
                    EventPayload::Form(map)
                } else {
                    EventPayload::Empty
                }
            }
            _ => EventPayload::Empty,
        }
    }

    /// Get text value if this is a text payload.
    ///
    /// Returns `Some(&str)` for `input` or `change` events on input/textarea elements.
    pub fn text(&self) -> Option<&str> {
        match self.payload() {
            EventPayload::Text(s) => Some(s.as_str()),
            _ => None,
        }
    }

    /// Get a data attribute value if this is a data payload.
    ///
    /// Returns `Some(&str)` for `click` events on elements with matching data-* attribute.
    ///
    /// # Example
    ///
    /// For an element with `data-id="5"`, `ctx.data("id")` returns `Some("5")`.
    pub fn data(&self, key: &str) -> Option<&str> {
        match self.payload() {
            EventPayload::Data(map) => map.get(key).map(|s| s.as_str()),
            _ => None,
        }
    }

    /// Get a form field value if this is a form payload.
    ///
    /// Returns `Some(&str)` for `submit` events on form elements.
    pub fn field(&self, name: &str) -> Option<&str> {
        match self.payload() {
            EventPayload::Form(map) => map.get(name).map(|s| s.as_str()),
            _ => None,
        }
    }

    /// Check if the payload is empty.
    pub fn is_empty(&self) -> bool {
        matches!(self.payload(), EventPayload::Empty)
    }

    /// Get the raw payload bytes.
    pub fn raw(&self) -> &[u8] {
        &self.raw
    }

    /// Get the handler parameter bytes.
    pub fn param_bytes(&self) -> &[u8] {
        &self.param_bytes
    }

    /// Check if this context has parameter bytes (from on_ref binding).
    pub fn has_params(&self) -> bool {
        !self.param_bytes.is_empty()
    }

    /// Extract an ItemRef from the parameter bytes.
    ///
    /// This is used with handlers bound via `on_ref()`. The ItemRef was
    /// encoded when binding the event and sent back with the event.
    ///
    /// # Example
    ///
    /// ```ignore
    /// #[handler]
    /// fn toggle_item(state: &mut TodoState, ctx: &EventContext) {
    ///     if let Some(item_ref) = ctx.item_ref::<TodoItem>() {
    ///         if let Some(item) = item_ref.get_mut(&mut state.items) {
    ///             item.done = !item.done;
    ///         }
    ///     }
    /// }
    /// ```
    pub fn item_ref<T: 'static>(&self) -> Option<ItemRef<T>> {
        if self.param_bytes.is_empty() {
            return None;
        }
        ItemRef::decode(&self.param_bytes).map(|(r, _)| r)
    }

    /// Attach the connection's session id (done by the server at dispatch).
    pub fn with_session(mut self, session: String) -> Self {
        self.session = Some(session);
        self
    }

    /// Attach the identity established at the WebSocket handshake by delegated
    /// authentication (done by the server at dispatch).
    pub fn with_identity(mut self, identity: Option<Identity>) -> Self {
        self.identity = identity;
        self
    }

    /// Attach the action this event drives (done by the server at dispatch), giving `defer()`
    /// the shared handle and key it needs to drive the lifecycle.
    pub fn with_action(mut self, shared: Arc<SharedServerState>, key: ActionKey) -> Self {
        self.action = Some(ActionSlot {
            shared,
            key,
            settlement: Default::default(),
        });
        self
    }

    /// Attach the connection's task registry (done by the server at dispatch).
    pub(crate) fn with_tasks(mut self, tasks: ConnectionTasks) -> Self {
        self.tasks = Some(tasks);
        self
    }

    /// Start a tokio task that lives as long as this connection: it is
    /// aborted when the connection closes (the client leaves, the heartbeat
    /// or re-validation fails, the server shuts down). The way to run
    /// per-user background work: start it in an
    /// [`on_connect`](crate::ServerWithRoot::on_connect) handler with what
    /// `identity()` / `session_id()` say, and reach the UI from it through
    /// the shared state (`SharedServerState::update_shared_if`).
    ///
    /// Returns `false`, dropping `fut` unpolled, when there is no live
    /// connection to tie it to: a context built by hand (tests), or the
    /// `on_disconnect` handler, which runs after the tasks were aborted.
    ///
    /// ```ignore
    /// #[handler]
    /// fn connected(me: &mut Me, ctx: &EventContext) {
    ///     let Some(user) = ctx.identity().map(|i| i.id().to_string()) else { return };
    ///     ctx.spawn(async move {
    ///         loop {
    ///             poll_inbox(&user).await;
    ///             tokio::time::sleep(Duration::from_secs(5)).await;
    ///         }
    ///     });
    /// }
    /// ```
    pub fn spawn<F>(&self, fut: F) -> bool
    where
        F: std::future::Future<Output = ()> + Send + 'static,
    {
        match &self.tasks {
            Some(tasks) => tasks.spawn(fut),
            None => false,
        }
    }

    /// Hand this action's completion off to background work.
    ///
    /// Call this in a handler that spawns a thread/task instead of finishing synchronously: it
    /// marks the action `Loading` (the triggering control immediately shows a spinner via the
    /// shared-state broadcast) and returns a [`Resolver`] to move into the background work. When
    /// that work finishes it calls [`Resolver::ok`] (control returns to idle) or
    /// [`Resolver::err`] (message surfaces). An action left unresolved is failed by a timeout
    /// backstop, so a control never spins forever.
    ///
    /// Reflection is automatic and complete: any control bound to a handler that defers shows
    /// loading and surfaces errors; one that never defers resolves in the same round-trip and
    /// shows nothing. Deferral is thus a runtime fact, not a guess from the handler's signature.
    pub fn defer(&self) -> Resolver {
        self.deferred.set(true);
        match &self.action {
            // Only claim the action + hand back a live resolver. Marking it `Loading` (and arming
            // the timeout) is done by the server *after* the handler returns — a `&mut SharedState`
            // handler runs holding the shared-cache write lock, and `set_action_loading` re-enters
            // that lock, so setting it here would self-deadlock. A resolver used before then
            // records its outcome in the slot's settlement, which the server applies instead of
            // `Loading` (see `settle_deferred`).
            Some(slot) => Resolver::new(
                Arc::clone(&slot.shared),
                slot.key.clone(),
                Arc::clone(&slot.settlement),
            ),
            None => Resolver::noop(),
        }
    }

    /// Whether the handler claimed this action for later (server-internal).
    pub(crate) fn was_deferred(&self) -> bool {
        self.deferred.get()
    }

    /// After a deferring handler returned (server-internal): apply a resolution made in it, or
    /// mark the action `Loading` and arm the timeout backstop.
    pub(crate) fn settle_deferred(&self) {
        if let Some(slot) = &self.action {
            crate::actions::settle_after_handler(&slot.settlement, &slot.shared, slot.key.clone());
        }
    }

    /// The connection's session id — stable across reconnects for the cookie
    /// TTL. Key per-user data in `#[storage(shared)]` handlers with this
    /// (the event itself carries no identity).
    pub fn session_id(&self) -> Option<&str> {
        self.session.as_deref()
    }

    /// Who this connection belongs to, when the server delegates authentication
    /// ([`ServerWithRoot::auth_with`](crate::ServerWithRoot::auth_with)). Fixed at the
    /// WebSocket handshake; the connection is closed if a later re-validation fails.
    /// `None` without delegated authentication.
    pub fn identity(&self) -> Option<&Identity> {
        self.identity.as_ref()
    }

    /// Get the item index from the parameter bytes.
    ///
    /// This is a lower-level alternative to `item_ref()` that just returns
    /// the index without type information.
    pub fn item_index(&self) -> Option<usize> {
        self.item_ref::<()>().map(|r| r.index())
    }
}

impl std::fmt::Debug for EventContext {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("EventContext")
            .field("payload", self.payload())
            .finish()
    }
}

